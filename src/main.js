// world-space, non-quantised, indexed position-only geometry
function toWorldPositions(mesh) {
  const g = mesh.geometry, pos = g.attributes.position, m = mesh.matrixWorld;
  const out = new Float32Array(pos.count * 3), v = new THREE.Vector3();
  for (let i = 0; i < pos.count; i++) { v.fromBufferAttribute(pos, i).applyMatrix4(m); out[3 * i] = v.x; out[3 * i + 1] = v.y; out[3 * i + 2] = v.z; }
  const idx = g.index ? Uint32Array.from(g.index.array) : Uint32Array.from({ length: pos.count }, (_, i) => i);
  return { pos: out, idx };
}
function mergePositions(list) {
  let nv = 0, ni = 0;
  for (const l of list) { nv += l.pos.length; ni += l.idx.length; }
  const pos = new Float32Array(nv), idx = new Uint32Array(ni);
  let ov = 0, oi = 0;
  for (const l of list) { pos.set(l.pos, ov); for (let i = 0; i < l.idx.length; i++) idx[oi + i] = l.idx[i] + ov / 3; ov += l.pos.length; oi += l.idx.length; }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  g.setIndex(new THREE.BufferAttribute(idx, 1));
  return g;
}

// ---------------- physics ----------------
const seg = new THREE.Line3(), box = new THREE.Box3();
const triPt = new THREE.Vector3(), capPt = new THREE.Vector3(), delta = new THREE.Vector3();
const fwd = new THREE.Vector3(), right = new THREE.Vector3(), move = new THREE.Vector3();

function wishDir() {
  camera.getWorldDirection(fwd); fwd.y = 0; fwd.normalize();
  right.crossVectors(fwd, camera.up).normalize();
  move.set(0, 0, 0);
  if (keys.KeyW || keys.ArrowUp) move.add(fwd);
  if (keys.KeyS || keys.ArrowDown) move.sub(fwd);
  if (keys.KeyD || keys.ArrowRight) move.add(right);
  if (keys.KeyA || keys.ArrowLeft) move.sub(right);
  return move.lengthSq() ? move.normalize() : move;
}

function step(dt) {
  const dir = wishDir();
  if (flying) {
    camera.getWorldDirection(fwd);
    const s = FLY * cheat.speed * (keys.ShiftLeft || keys.ShiftRight ? 2.5 : 1);
    player.position.addScaledVector(dir, s * dt);
    if (keys.Space) player.position.y += s * dt;
    if (keys.KeyC) player.position.y -= s * dt;
    return;
  }
  crouching = !!(keys.ControlLeft || keys.ControlRight || keys.KeyC);
  sprinting = !!(keys.ShiftLeft || keys.ShiftRight) && !crouching && !exhausted && stamina > 0 && dir.lengthSq() > 0;
  const speed = (crouching ? WALK * 0.45 : sprinting ? RUN : WALK) * cheat.speed;
  if (onGround) vel.y = Math.min(vel.y, 0) ; // stick to floors / stairs
  vel.y += GRAVITY * dt;
  player.position.addScaledVector(vel, dt);
  player.position.addScaledVector(dir, speed * dt);

  // capsule vs BVH
  seg.start.copy(player.position);
  seg.end.copy(player.position).y -= PLAYER.segment;
  box.makeEmpty().expandByPoint(seg.start).expandByPoint(seg.end);
  box.min.addScalar(-PLAYER.radius); box.max.addScalar(PLAYER.radius);
  collider.geometry.boundsTree.shapecast({
    intersectsBounds: (b) => b.intersectsBox(box),
    intersectsTriangle: (tri) => {
      const d = tri.closestPointToSegment(seg, triPt, capPt);
      if (d < PLAYER.radius) {
        const depth = PLAYER.radius - d;
        const n = capPt.sub(triPt).normalize();
        seg.start.addScaledVector(n, depth);
        seg.end.addScaledVector(n, depth);
      }
    },
  });
  delta.subVectors(seg.start, player.position);
  onGround = delta.y > Math.abs(dt * vel.y * 0.25);
  const off = Math.max(0, delta.length() - 1e-5);
  delta.normalize().multiplyScalar(off);
  player.position.add(delta);
  if (onGround) vel.set(0, 0, 0);
  else { delta.normalize(); vel.addScaledVector(delta, -delta.dot(vel)); }
  // door leaves (dynamic, not in the BVH)
  const feetY = player.position.y - PLAYER.segment - PLAYER.radius;
  roomDoors.collide(player.position, feetY + 0.05, player.position.y + PLAYER.radius, PLAYER.radius);

  if (player.position.y < -30) respawn();
}

// ---------------- loop ----------------
const floorEl = document.getElementById('floor'), modeEl = document.getElementById('mode'), hintEl = document.getElementById('hint');
const clock = new THREE.Clock();
let bobT = 0, bobAmp = 0, pickFrame = 0, looked = null;
// walking motion state
let stepSide = 0, runK = 0, airVy = 0, landDip = 0, landV = 0, lagX = 0, lagY = 0, lastYaw = 0, lastPitch = 0, camRoll = 0, camPitch = 0, idleT = 0;
const bobRight = new THREE.Vector3(), bobEuler = new THREE.Euler(0, 0, 0, 'YXZ');
function frame() {
  const rawDt = Math.min(clock.getDelta(), 0.05);
  const dt = rawDt * cheat.timeScale;                 // you
  const wdt = cheat.frozen ? 0 : dt;                  // the world
  if (collider) {
    const before = player.position.clone();
    const wasGround = onGround;
    if (controls.isLocked && state === 'play') for (let i = 0; i < SUBSTEPS; i++) { step(dt / SUBSTEPS); if (!onGround) airVy = Math.min(airVy, vel.y); }
    if (onGround && !wasGround && !flying) {                 // landing: knees give a little, then spring back
      landV -= Math.min(2.2, Math.max(0, -airVy - 2) * 0.35); airVy = 0;
      if (state === 'play') { audio.footstep(true); landNoiseT = 0.4; }
    }
    if (state === 'menu') menuCamera(dt);
    else if (state !== 'caught') camera.position.copy(player.position).y += PLAYER.eye;
    else camera.position.copy(caughtPos);
    crouchK += ((crouching && state === 'play' ? 1 : 0) - crouchK) * Math.min(1, dt * 8);
    if (state !== 'menu' && state !== 'caught') camera.position.y -= crouchK * 0.45;
    // head bob while walking
    const speed = Math.hypot(player.position.x - before.x, player.position.z - before.z) / Math.max(dt, 1e-4);
    const moving = state === 'play' && onGround && !flying && speed > 0.5;
    // Walking motion. One cycle of bobT = two steps. The head is lowest as each foot lands and highest mid-stride,
    // sways toward the planted foot, and rolls a touch with it; running is bigger and quicker. Footsteps fire
    // on the dip so sound and motion line up.
    runK += ((speed > 4.5 ? 1 : 0) - runK) * Math.min(1, dt * 4);
    const stepsPerSec = moving ? speed / (1.05 + runK * 0.55) : 0;        // stride ~1.05 m walking, ~1.6 m running
    bobT += dt * Math.PI * stepsPerSec;
    bobAmp += ((moving ? 1 : 0) - bobAmp) * Math.min(1, dt * (moving ? 5 : 3));
    const side = Math.floor(bobT / Math.PI);
    if (moving && side !== stepSide && !crouching) audio.footstep(runK > 0.5);
    stepSide = side;
    const s1 = Math.sin(bobT), lift = Math.abs(s1);
    const A = (0.05 + runK * 0.035) * bobAmp;                              // vertical bounce
    camera.getWorldDirection(bobRight); bobRight.set(-bobRight.z, 0, bobRight.x).normalize();
    camera.position.y += (lift - 0.64) * A;
    camera.position.addScaledVector(bobRight, s1 * (0.028 + runK * 0.02) * bobAmp);
    // idle breathing when standing still
    idleT += dt;
    camera.position.y += Math.sin(idleT * 1.55) * 0.007 * (1 - bobAmp);
    // landing spring
    landV += (-landDip * 90 - landV * 14) * dt; landDip += landV * dt;
    camera.position.y += landDip * 0.12;
    camRoll = s1 * (0.009 + runK * 0.01) * bobAmp + Math.sin(idleT * 0.8) * 0.0015 * (1 - bobAmp);
    camPitch = -(1 - lift) * 0.006 * bobAmp + landDip * 0.05;
    // the torch lags behind quick turns and swings with your steps
    bobEuler.setFromQuaternion(camera.quaternion);
    let dYaw = bobEuler.y - lastYaw; if (dYaw > Math.PI) dYaw -= Math.PI * 2; if (dYaw < -Math.PI) dYaw += Math.PI * 2;
    const dPitch = bobEuler.x - lastPitch; lastYaw = bobEuler.y; lastPitch = bobEuler.x;
    lagX += (Math.max(-0.6, Math.min(0.6, dYaw * 7)) - lagX) * Math.min(1, dt * 8);
    lagY += (Math.max(-0.5, Math.min(0.5, -dPitch * 7)) - lagY) * Math.min(1, dt * 8);
    torchTarget.position.set(0.1 + lagX * 2.5 + s1 * 0.12 * bobAmp, -0.02 + lagY * 2.5 - (1 - lift) * 0.1 * bobAmp, -6);

    // flashlight: occasional brief flicker
    torchFlicker -= wdt;
    if (torchFlicker < -8 && Math.random() < wdt * 0.15) torchFlicker = 0.35;
    const tp = cheat.torchPower;
    torch.intensity = torchOn && !(director.torchOut > 0) ? (torchFlicker > 0 && wdt > 0 ? (Math.random() < 0.5 ? tp * 0.07 : tp * 0.6) : tp) : 0;
    // corridor lights: flicker, buzz louder near a live one
    let nearLight = 0;
    for (const f of flickers) {
      if (wdt > 0) {
        f.t += wdt;
        const on = cheat.lights === 'on' || (cheat.lights === 'flicker' && !f.dead && (Math.sin(f.t * 1.3) > -0.7 || Math.random() < 0.3) && Math.random() > 0.04);
        f.pl.intensity = on ? f.base * (cheat.lights === 'on' ? 1 : 0.85 + Math.random() * 0.15) : 0;
      }
      const on = f.pl.intensity > 0;
      const d = f.pl.position.distanceTo(camera.position);
      if (on && d < 8) nearLight = Math.max(nearLight, 1 - d / 8);
    }
    if (state === 'play') audio.update(dt, { moving, running: speed > 4.5, nearLight, frozen: cheat.frozen });
    // stamina
    if (state === 'play') {
      if (sprinting && moving) { stamina -= dt / 6; if (stamina <= 0) { stamina = 0; exhausted = true; audio.breath(0); } }
      else stamina = Math.min(1, stamina + dt / (exhausted ? 10 : 8));
      if (exhausted && stamina > 0.35) exhausted = false;
      staminaEl.style.opacity = stamina < 0.999 ? 1 : 0;
      staminaEl.firstChild.style.width = (stamina * 100).toFixed(1) + '%';
      staminaEl.classList.toggle('low', exhausted);
      health.update(wdt);
      if (health.hearts === 1 && wdt > 0) { lowBeatT -= wdt; if (lowBeatT <= 0) { audio.heartbeat(1, 1.15); lowBeatT = 1.6; } }
    }
    // Manju, Mutty and Zoya
    landNoiseT -= dt;
    const noise = !moving ? (landNoiseT > 0 ? 9 : 0) : crouching ? 0 : speed > 4.5 ? 12 : 4;
    if (state === 'play' && wdt > 0 && !devcon?.open) {
      if (manju.state === 'off' && manju.ready && nav?.ready && manju.enabled) { manjuGrace -= wdt; if (manjuGrace <= 0) manju.spawnFar(feetPos()); }
      camera.getWorldDirection(camDir);
      const ctx = { feet: feetPos(), eyePos: camera.position, camDir, torchOn, torchI: torch.intensity, noise, crouch: crouching, hidden: false };
      manju.update(wdt, ctx);
      if (state === 'play') mutty.update(wdt, ctx);
      if (state === 'play') zoya.update(wdt, ctx);
      if (state === 'play') voiceTick(wdt, ctx);
      // bring the two floor-bound characters in after the grace period
      charSpawnT -= wdt;
      if (charGrace > 0) charGrace -= wdt;
      if (charGrace <= 0 && charSpawnT <= 0) {
        charSpawnT = 1;
        if (mutty.state === 'off' && mutty.ready && mutty.nav?.ready) mutty.spawnFar(ctx.feet);
        if (zoya.state === 'off' && zoya.ready && zoya.nav?.ready) zoya.spawnFar(ctx.feet);
      }
    }
    if (state === 'caught') caughtUpdate(rawDt);
    const threat = (state === 'play' || state === 'caught') ? Math.max(manju.alert, mutty.alert) : 0;
    const prox = state === 'play' ? Math.max(manju.prox, mutty.prox) : 0;
    audio.setThreat(state === 'play' || (state === 'caught' && !deadShown) ? threat : 0, state === 'play' ? prox : 0);
    retro.setChase(state === 'caught' ? 1 : threat);
    if (threat > 0.15 && director.fig) director.vanish(false);
    if (state === 'play' && wdt > 0 && !devcon?.open && threat < 0.15) director.update(wdt, { moving, torchOn });
    // fog follows you in and out of the building
    if ((pickFrame & 7) === 0) indoorK += ((director.indoors() ? 1 : 0) - indoorK) * 0.25;
    scene.fog.color.lerpColors(FOG_OUT, FOG_IN, indoorK); scene.background.copy(scene.fog.color);
    scene.fog.density = cheat.fog ?? (0.026 + 0.064 * indoorK);
    retro.mist.uMist.value = cheat.fog === 0 ? 0 : 0.14 * (1 - indoorK);     // ground mist only outdoors
    sky.material.uniforms.uHorizon.value.copy(scene.fog.color);
    beam.visible = torch.intensity > 1;
    beam.material.uniforms.uStrength.value = 0.06 * torch.intensity / 6;

    // doors swing open when the player is near
    for (const d of doors) {
      const near = DOORS_OPEN && d.centre.distanceTo(player.position) < 3.2;
      d.open += ((near ? 1 : 0) - d.open) * Math.min(1, wdt * 4);
      d.pivot.rotation.y = d.dir * d.open * Math.PI * 0.55;
    }

    roomDoors.update(wdt);
    if (++pickFrame % 4 === 0) looked = controls.isLocked ? roomDoors.pick(camera) : null;
    hintEl.style.display = looked ? 'block' : 'none';
    if (looked) hintEl.textContent = (looked.target ? 'E  close' : 'E  open') + (looked.r.kind === 'glass' ? ' — stairs' : '');
    const feet = player.position.y - PLAYER.segment - PLAYER.radius;
    let label = FLOORS[0][1];
    for (const [h, n] of FLOORS) if (feet > h) label = n;
    floorEl.textContent = label;
    modeEl.textContent = flying ? 'Fly mode (F to land)' : 'Walking';
  }
  menu.update(rawDt);
  sky.position.copy(camera.position);
  if (audio.ctx) voices.update(listener());
  camera.rotateZ(camRoll); camera.rotateX(camPitch);
  retro.render(rawDt);
  camera.rotateX(-camPitch); camera.rotateZ(-camRoll);
  requestAnimationFrame(frame);
}
