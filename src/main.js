new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).load('./public/building.glb?v=' + Date.now(), async (gltf) => {
  const root = gltf.scene;
  scene.add(root);
  root.updateMatrixWorld(true);

  const staticGeoms = [];
  root.traverse((o) => {
    if (!o.isMesh) return;
    o.castShadow = true; o.receiveShadow = true;
  });

  for (const name of ['doorL', 'doorR']) {
    const node = root.getObjectByName(name);
    if (!node) continue;
    // hinge on the outer vertical edge of each leaf
    const box = new THREE.Box3().setFromObject(node);
    const hingeX = name === 'doorL' ? box.min.x : box.max.x;
    const pivot = new THREE.Group();
    pivot.position.set(hingeX, 0, (box.min.z + box.max.z) / 2);
    root.add(pivot);
    pivot.attach(node);
    doors.push({ pivot, open: 0, dir: name === 'doorL' ? 1 : -1, centre: box.getCenter(new THREE.Vector3()) });
  }

  // collision geometry: everything except the doors, plus the ground plane, in world space
  root.updateMatrixWorld(true);
  const isDoor = (o) => { for (let p = o; p; p = p.parent) if (p.name === 'doorL' || p.name === 'doorR') return true; return false; };
  root.traverse((o) => { if (o.isMesh && (!DOORS_OPEN || !isDoor(o))) staticGeoms.push(toWorldPositions(o)); });
  ground.updateMatrixWorld(); staticGeoms.push(toWorldPositions(ground));
  const merged = mergePositions(staticGeoms);
  merged.boundsTree = new MeshBVH(merged);
  collider = new THREE.Mesh(merged);   // never added to the scene
  collider.updateMatrixWorld();
  roomDoors.occluder = collider;

  respawn();
  await doorsLoaded;
  retro.apply(scene);
  ready = true;
  menu.setReady();
}, undefined, (err) => { document.getElementById('loading').textContent = 'Failed to load building: ' + err; });

// world-space, non-quantised, indexed position-only geometry
function toWorldPositions(mesh) {
  const g = mesh.geometry, pos = g.attributes.position, m = mesh.matrixWorld;
  const out = new Float32Array(pos.count * 3), v = new THREE.Vector3();
  for (let i = 0; i < pos.count; i++) { v.fromBufferAttribute(pos, i).applyMatrix4(m); out[3 * i] = v.x; out[3 * i + 1] = v.y; out[3 * i + 2] = v.z; }
  const idx = g.index ? Uint32Array.from(g.index.array) : Uint32Array.from({ length: pos.count }, (_, i) => i);
  return { pos: out, idx };
}
function mergePositions(list) {
  let nv = 0, ni = 0;
  for (const l of list) { nv += l.pos.length; ni += l.idx.length; }
  const pos = new Float32Array(nv), idx = new Uint32Array(ni);
  let ov = 0, oi = 0;
  for (const l of list) { pos.set(l.pos, ov); for (let i = 0; i < l.idx.length; i++) idx[oi + i] = l.idx[i] + ov / 3; ov += l.pos.length; oi += l.idx.length; }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  g.setIndex(new THREE.BufferAttribute(idx, 1));
  return g;
}

// ---------------- physics ----------------
const seg = new THREE.Line3(), box = new THREE.Box3();
const triPt = new THREE.Vector3(), capPt = new THREE.Vector3(), delta = new THREE.Vector3();
const fwd = new THREE.Vector3(), right = new THREE.Vector3(), move = new THREE.Vector3();

function wishDir() {
  camera.getWorldDirection(fwd); fwd.y = 0; fwd.normalize();
  right.crossVectors(fwd, camera.up).normalize();
  move.set(0, 0, 0);
  if (keys.KeyW || keys.ArrowUp) move.add(fwd);
  if (keys.KeyS || keys.ArrowDown) move.sub(fwd);
  if (keys.KeyD || keys.ArrowRight) move.add(right);
  if (keys.KeyA || keys.ArrowLeft) move.sub(right);
  return move.lengthSq() ? move.normalize() : move;
}

function step(dt) {
  const dir = wishDir();
  if (flying) {
    camera.getWorldDirection(fwd);
    const s = FLY * cheat.speed * (keys.ShiftLeft || keys.ShiftRight ? 2.5 : 1);
    player.position.addScaledVector(dir, s * dt);
    if (keys.Space) player.position.y += s * dt;
    if (keys.KeyC) player.position.y -= s * dt;
    return;
  }
  const speed = (keys.ShiftLeft || keys.ShiftRight ? RUN : WALK) * cheat.speed;
  if (onGround) vel.y = Math.min(vel.y, 0) ; // stick to floors / stairs
  vel.y += GRAVITY * dt;
  player.position.addScaledVector(vel, dt);
  player.position.addScaledVector(dir, speed * dt);

  // capsule vs BVH
  seg.start.copy(player.position);
  seg.end.copy(player.position).y -= PLAYER.segment;
  box.makeEmpty().expandByPoint(seg.start).expandByPoint(seg.end);
  box.min.addScalar(-PLAYER.radius); box.max.addScalar(PLAYER.radius);
  collider.geometry.boundsTree.shapecast({
    intersectsBounds: (b) => b.intersectsBox(box),
    intersectsTriangle: (tri) => {
      const d = tri.closestPointToSegment(seg, triPt, capPt);
      if (d < PLAYER.radius) {
        const depth = PLAYER.radius - d;
        const n = capPt.sub(triPt).normalize();
        seg.start.addScaledVector(n, depth);
        seg.end.addScaledVector(n, depth);
      }
    },
  });
  delta.subVectors(seg.start, player.position);
  onGround = delta.y > Math.abs(dt * vel.y * 0.25);
  const off = Math.max(0, delta.length() - 1e-5);
  delta.normalize().multiplyScalar(off);
  player.position.add(delta);
  if (onGround) vel.set(0, 0, 0);
  else { delta.normalize(); vel.addScaledVector(delta, -delta.dot(vel)); }
  // door leaves (dynamic, not in the BVH)
  const feetY = player.position.y - PLAYER.segment - PLAYER.radius;
  roomDoors.collide(player.position, feetY + 0.05, player.position.y + PLAYER.radius, PLAYER.radius);

  if (player.position.y < -30) respawn();
}

// ---------------- loop ----------------
const floorEl = document.getElementById('floor'), modeEl = document.getElementById('mode'), hintEl = document.getElementById('hint');
const clock = new THREE.Clock();
let bobT = 0, bobAmp = 0, pickFrame = 0, looked = null;
function frame() {
  const rawDt = Math.min(clock.getDelta(), 0.05);
  const dt = rawDt * cheat.timeScale;                 // you
  const wdt = cheat.frozen ? 0 : dt;                  // the world
  if (collider) {
    const before = player.position.clone();
    if (controls.isLocked) for (let i = 0; i < SUBSTEPS; i++) step(dt / SUBSTEPS);
    if (state === 'menu') menuCamera(dt);
    else camera.position.copy(player.position).y += PLAYER.eye;
    // head bob while walking
    const speed = Math.hypot(player.position.x - before.x, player.position.z - before.z) / Math.max(dt, 1e-4);
    const moving = state === 'play' && onGround && !flying && speed > 0.5;
    bobT += moving ? dt * (speed > 4.5 ? 11 : 7.5) : 0;
    bobAmp += ((moving ? 1 : 0) - bobAmp) * Math.min(1, dt * 6);
    camera.position.y += Math.sin(bobT) * 0.035 * bobAmp;
    camera.position.x += Math.cos(bobT * 0.5) * 0.02 * bobAmp;

    // flashlight: occasional brief flicker
    torchFlicker -= wdt;
    if (torchFlicker < -8 && Math.random() < wdt * 0.15) torchFlicker = 0.35;
    const tp = cheat.torchPower;
    torch.intensity = torchOn && !(director.torchOut > 0) ? (torchFlicker > 0 && wdt > 0 ? (Math.random() < 0.5 ? tp * 0.07 : tp * 0.6) : tp) : 0;
    // corridor lights: flicker, buzz louder near a live one
    let nearLight = 0;
    for (const f of flickers) {
      if (wdt > 0) {
        f.t += wdt;
        const on = cheat.lights === 'on' || (cheat.lights === 'flicker' && !f.dead && (Math.sin(f.t * 1.3) > -0.7 || Math.random() < 0.3) && Math.random() > 0.04);
        f.pl.intensity = on ? f.base * (cheat.lights === 'on' ? 1 : 0.85 + Math.random() * 0.15) : 0;
      }
      const on = f.pl.intensity > 0;
      const d = f.pl.position.distanceTo(camera.position);
      if (on && d < 8) nearLight = Math.max(nearLight, 1 - d / 8);
    }
    if (state === 'play') audio.update(dt, { moving, running: speed > 4.5, nearLight });
    if (state === 'play' && wdt > 0) director.update(wdt, { moving, torchOn });
    // fog follows you in and out of the building
    if ((pickFrame & 7) === 0) indoorK += ((director.indoors() ? 1 : 0) - indoorK) * 0.25;
    scene.fog.color.lerpColors(FOG_OUT, FOG_IN, indoorK); scene.background.copy(scene.fog.color);
    scene.fog.density = cheat.fog ?? (0.06 + 0.03 * indoorK);
    beam.visible = torch.intensity > 1;
    beam.material.uniforms.uStrength.value = 0.06 * torch.intensity / 6;

    // doors swing open when the player is near
    for (const d of doors) {
      const near = DOORS_OPEN && d.centre.distanceTo(player.position) < 3.2;
      d.open += ((near ? 1 : 0) - d.open) * Math.min(1, wdt * 4);
      d.pivot.rotation.y = d.dir * d.open * Math.PI * 0.55;
    }

    roomDoors.update(wdt);
    if (++pickFrame % 4 === 0) looked = controls.isLocked ? roomDoors.pick(camera) : null;
    hintEl.style.display = looked ? 'block' : 'none';
    if (looked) hintEl.textContent = (looked.target ? 'E  close' : 'E  open') + (looked.r.kind === 'glass' ? ' — stairs' : '');
    const feet = player.position.y - PLAYER.segment - PLAYER.radius;
    let label = FLOORS[0][1];
    for (const [h, n] of FLOORS) if (feet > h) label = n;
    floorEl.textContent = label;
    modeEl.textContent = flying ? 'Fly mode (F to land)' : 'Walking';
  }
  menu.update(rawDt);
  mist.update(wdt, camera, clock.elapsedTime);
  retro.render(rawDt);
  requestAnimationFrame(frame);
}
frame();

